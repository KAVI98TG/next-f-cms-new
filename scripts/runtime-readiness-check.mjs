import fs from "node:fs";
import path from "node:path";
const pass=[]; const fail=[];
const check=(label,ok)=>ok?pass.push(label):fail.push(label);
const read=(p)=>fs.readFileSync(p,"utf8");
const exists=(p)=>fs.existsSync(p);
const pkg=JSON.parse(read("package.json"));
const lock=JSON.parse(read("package-lock.json"));
const version=read("VERSION").trim();
const appVersion=read("src/app/version.ts");
const master=read("docs/planning/NEXT-F-CMS-UPGRADE-MASTER-PLAN.md");
const semverAtLeast020=(value)=>{const [a,b,c]=value.split(".").map(Number);return a>0||(a===0&&(b>20||(b===20&&c>=0)));};
check("package version remains V0.20+",semverAtLeast020(pkg.version));
check("lock version remains V0.20+",semverAtLeast020(lock.version)&&semverAtLeast020(lock.packages?.[""]?.version||"0.0.0"));
check("VERSION remains V0.20+",semverAtLeast020(version));
const appVersionMatch=appVersion.match(/APP_VERSION = "([^"]+)"/);
check("app version remains V0.20+",Boolean(appVersionMatch&&semverAtLeast020(appVersionMatch[1])));
check("release label is defined",/APP_RELEASE = "[^"]+"/.test(appVersion));
check("runtime QA script wired",pkg.scripts?.["check:runtime-readiness"]==="node scripts/runtime-readiness-check.mjs");
check("lockfile exists",exists("package-lock.json"));
check("Vite config exists",exists("vite.config.ts"));
check("TypeScript build configs exist",exists("tsconfig.json")&&exists("tsconfig.app.json")&&exists("tsconfig.node.json"));
check("production build command includes tsc",String(pkg.scripts?.build).includes("tsc -b"));
check("production build command includes vite",String(pkg.scripts?.build).includes("vite build"));
for(const dep of ["react","react-dom","lucide-react"]) check(`runtime dependency ${dep} locked`,Boolean(lock.packages?.[`node_modules/${dep}`]?.version));
for(const dep of ["typescript","vite","@vitejs/plugin-react","@types/react","@types/react-dom","@types/node"]) check(`build dependency ${dep} locked`,Boolean(lock.packages?.[`node_modules/${dep}`]?.version));
check("smoke QA document exists",exists("docs/releases/V0.20.0-RUNTIME-RELEASE-HARDENING.md"));
check("QA report exists",exists("docs/qa/QA-V0.20.0.md"));
check("master plan records phase 8.5",master.includes("Phase 8.5"));
const sourceFiles=[];
const walk=(dir)=>{for(const ent of fs.readdirSync(dir,{withFileTypes:true})){const p=path.join(dir,ent.name);if(ent.isDirectory())walk(p);else if(/\.(ts|tsx)$/.test(ent.name))sourceFiles.push(p)}};
walk("src");
check("application source is non-trivial",sourceFiles.length>=180);
const browserStores=sourceFiles.filter((p)=>read(p).includes("localStorage"));
const toPosixPath=(value)=>value.split(path.sep).join("/");
check("browser persistence is limited to local adapters/preferences",browserStores.length>0&&browserStores.every((p)=>{
  const normalized=toPosixPath(p);
  return normalized.includes("app/auth")||normalized.includes("app/theme")||normalized.includes("services/production");
}));
console.log("NEXT F CMS V0.20.0 Runtime & Release Hardening check");
for(const item of pass) console.log(`PASS  ${item}`);
for(const item of fail) console.error(`FAIL  ${item}`);
console.log(`\n${pass.length} passed, ${fail.length} failed`);
if(fail.length) process.exit(1);
